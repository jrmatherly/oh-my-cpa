#!/bin/bash
# PreToolUse hook for Edit|Write. Denies edits that AGENTS.md forbids without
# exception: applied SQL migrations, the CLAUDE.md symlink, and the generated SPA.
set -euo pipefail

input=$(cat)
file_path=$(printf '%s' "$input" | jq -r '.tool_input.file_path // empty')
[ -z "$file_path" ] && exit 0

root="${CLAUDE_PROJECT_DIR:-$(pwd)}"
rel="${file_path#"$root"/}"

deny() {
  jq -n --arg reason "$1" '{hookSpecificOutput:{hookEventName:"PreToolUse",permissionDecision:"deny",permissionDecisionReason:$reason}}'
  exit 0
}

case "$rel" in
  CLAUDE.md)
    deny "CLAUDE.md is a symlink to AGENTS.md. Edit AGENTS.md instead." ;;
  internal/web/dist/*)
    deny "internal/web/dist is generated by 'pnpm build' (scripts/sync-web-dist.mjs). Edit web/src and rebuild." ;;
  migrations/*.sql)
    # A migration tracked in git has been applied somewhere; migrations are forward-only.
    if git -C "$root" ls-files --error-unmatch -- "$rel" >/dev/null 2>&1; then
      next=$(ls "$root/migrations" | grep -oE '^[0-9]+' | sort -n | tail -1 | awk '{printf "%03d", $1 + 1}')
      deny "$rel is an applied migration and migrations are forward-only. Add migrations/${next}_<name>.sql instead."
    fi ;;
esac
exit 0
